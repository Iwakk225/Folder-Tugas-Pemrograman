#include <stdio.h>

int main(void) {
    int a, b, hasil;

    a = 10;
    b = 5;
    hasil = a + b;
    printf("a + b = %d\n", hasil);

    a = 15;
    b = 5;
    hasil = a - b;
    printf("a - b = %d\n", hasil);

    a = 5;
    b = 2;
    hasil = a * b;
    printf("a * b = %d\n", hasil);

    a = 50;
    b = 5;
    hasil = a / b;
    printf("a / b = %d\n", hasil);

    return 0;
}
